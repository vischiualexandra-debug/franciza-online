// Textul unei variante: codul cunoscut → traducere; altfel textul scris de om („Altceva”).
export function optionLabel(t, field, value) {
  if (value === null || value === undefined || value === '') return '—';
  const key = `o_${field}_${value}`;
  const s = t(key);
  return s === key ? value : s;
}
